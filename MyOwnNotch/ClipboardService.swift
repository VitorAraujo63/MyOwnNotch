//
//  ClipboardService.swift
//  MyOwnNotch
//
//  Histórico da área de transferência (somente memória, nunca persistido).
//  Detecta mudanças por polling leve de NSPasteboard.changeCount (não existe
//  notificação pública) e ignora conteúdo sensível/marcado como transitório.
//

import AppKit
import Combine

@MainActor
final class ClipboardService: ObservableObject {

    @Published private(set) var items: [ClipboardItem] = []
    @Published private(set) var isRunning = false

    nonisolated static let maxUnpinned = 60
    nonisolated static let maxTextLength = 10_000
    nonisolated static let thumbnailMaxSide: CGFloat = 160
    nonisolated static let maxPinned = 30
    nonisolated static let maxImageBytes = 30 * 1024 * 1024
    nonisolated static let unpinnedTTL: TimeInterval = 3600

    /// Tipos que sinalizam conteúdo sensível/efêmero (convenção nspasteboard.org + 1Password).
    nonisolated static let blockedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.agilebits.onepassword7",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "com.nspasteboard.ConcealedType"
    ]

    /// Apps de senha: nunca capturar quando são o app em primeiro plano (comparação case-insensitive).
    nonisolated static let blockedBundlePrefixes: [String] = [
        "com.agilebits.", "com.1password.", "com.bitwarden.", "com.lastpass.",
        "com.dashlane.", "org.keepassxc.", "com.apple.keychainaccess",
        "com.apple.Passwords", "in.sinew.Enpass", "com.keepersecurity.",
        "com.markmcguill.strongbox", "me.proton.pass", "com.hicknhacksoftware.MacPass",
        "com.outercorner.Secrets", "com.keepassium", "com.nordsec.nordpass"
    ].map { $0.lowercased() }

    nonisolated static func isBlockedBundle(_ bid: String) -> Bool {
        let l = bid.lowercased()
        return blockedBundlePrefixes.contains { l.hasPrefix($0) }
    }

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private var imageTask: Task<Void, Never>?
    private var workspaceTokens: [NSObjectProtocol] = []
    private var distributedTokens: [NSObjectProtocol] = []

    init() { lastChangeCount = NSPasteboard.general.changeCount }

    private var enabled: Bool {
        UserDefaults.standard.object(forKey: SettingsKey.clipboardEnabled) as? Bool ?? true
    }

    // MARK: - Ciclo de vida

    func start() {
        guard enabled, !isRunning else { return }
        lastChangeCount = pasteboard.changeCount   // não captura o que já estava lá antes de ligar
        isRunning = true
        startTimer()
        installObservers()
    }

    func stop() {
        removeObservers()
        stopTimer()
        imageTask?.cancel(); imageTask = nil
        isRunning = false
    }

    private func startTimer() {
        guard timer == nil else { return }
        let t = Timer(timeInterval: 1.0, repeats: true) { _ in
            MainActor.assumeIsolated { [weak self] in self?.poll() }
        }
        t.tolerance = 0.5
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func stopTimer() { timer?.invalidate(); timer = nil }

    private func pauseForSleep() { stopTimer(); imageTask?.cancel(); imageTask = nil }

    private func resumeAfterSleep() {
        guard isRunning else { return }
        lastChangeCount = pasteboard.changeCount
        startTimer()
    }

    private func installObservers() {
        guard workspaceTokens.isEmpty else { return }
        let ws = NSWorkspace.shared.notificationCenter
        func add(_ name: Notification.Name, _ block: @escaping @MainActor (ClipboardService) -> Void) {
            let tok = ws.addObserver(forName: name, object: nil, queue: .main) { [weak self] _ in
                MainActor.assumeIsolated { if let self { block(self) } }
            }
            workspaceTokens.append(tok)
        }
        add(NSWorkspace.willSleepNotification) { $0.clearUnpinned(); $0.pauseForSleep() }
        add(NSWorkspace.screensDidSleepNotification) { $0.pauseForSleep() }
        add(NSWorkspace.sessionDidResignActiveNotification) { $0.pauseForSleep() }
        add(NSWorkspace.didWakeNotification) { $0.resumeAfterSleep() }
        add(NSWorkspace.screensDidWakeNotification) { $0.resumeAfterSleep() }
        add(NSWorkspace.sessionDidBecomeActiveNotification) { $0.resumeAfterSleep() }
        add(NSWorkspace.didActivateApplicationNotification) { $0.timer != nil ? $0.poll() : () }

        let dc = DistributedNotificationCenter.default()
        let lock = dc.addObserver(forName: Notification.Name("com.apple.screenIsLocked"),
                                  object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated { self?.clearUnpinned() }
        }
        distributedTokens.append(lock)
    }

    private func removeObservers() {
        let ws = NSWorkspace.shared.notificationCenter
        workspaceTokens.forEach { ws.removeObserver($0) }
        workspaceTokens.removeAll()
        distributedTokens.forEach { DistributedNotificationCenter.default().removeObserver($0) }
        distributedTokens.removeAll()
    }

    // MARK: - Ações

    func copyToPasteboard(_ item: ClipboardItem) {
        if item.kind == .file {
            // Arquivo que não existe mais: remove o item em vez de escrever um path inválido.
            guard let p = item.text, FileManager.default.fileExists(atPath: p) else {
                remove(item.id); return
            }
        }
        pasteboard.clearContents()
        switch item.kind {
        case .text, .link, .color:
            if let t = item.text { pasteboard.setString(t, forType: .string) }
        case .file:
            if let p = item.text { pasteboard.writeObjects([URL(fileURLWithPath: p) as NSURL]) }
        case .image:
            if let d = item.imagePNG { pasteboard.setData(d, forType: .png) }
        }
        lastChangeCount = pasteboard.changeCount   // evita re-captura
        // Sobe para o topo (nova data; fixados continuam primeiro)
        if let idx = items.firstIndex(where: { $0.id == item.id }) {
            let old = items[idx]
            items[idx] = ClipboardItem(id: old.id, kind: old.kind, text: old.text, imagePNG: old.imagePNG,
                                       sourceApp: old.sourceApp, date: Date(), isPinned: old.isPinned)
            items = Self.ordered(items)
        }
    }

    func togglePin(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        if !items[i].isPinned, items.filter(\.isPinned).count >= Self.maxPinned { return }
        items[i].isPinned.toggle()
        items = Self.ordered(items)
    }

    func remove(_ id: UUID) { items.removeAll { $0.id == id } }

    func clearUnpinned() { if items.contains(where: { !$0.isPinned }) { items.removeAll { !$0.isPinned } } }

    private func expireOld() {
        let cutoff = Date().addingTimeInterval(-Self.unpinnedTTL)
        if items.contains(where: { !$0.isPinned && $0.date < cutoff }) {
            items.removeAll { !$0.isPinned && $0.date < cutoff }
        }
    }

    // MARK: - Captura

    private func poll() {
        expireOld()
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        capture(changeCount: count)
    }

    private func capture(changeCount before: Int) {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard !types.isEmpty, types.isDisjoint(with: Self.blockedTypes) else { return }

        let front = NSWorkspace.shared.frontmostApplication
        if let bid = front?.bundleIdentifier, Self.isBlockedBundle(bid) { return }
        let source = front?.localizedName

        // Arquivo
        if types.contains("public.file-url") {
            let urls = (pasteboard.readObjects(forClasses: [NSURL.self],
                                               options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
            guard pasteboard.changeCount == before else { return }   // TOCTOU
            // Vários arquivos: guarda só o primeiro (um path por item; evita path inválido com "\n").
            if let first = urls.first {
                insert(kind: .file, text: first.path, png: nil, source: source)
                return
            }
        }
        // Texto
        if types.contains("public.utf8-plain-text") || types.contains("NSStringPboardType") {
            guard var text = pasteboard.string(forType: .string) else { return }
            guard pasteboard.changeCount == before else { return }   // TOCTOU
            guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
            if Self.looksLikeSecret(text) { return }
            if text.count > Self.maxTextLength { text = String(text.prefix(Self.maxTextLength)) }
            insert(kind: Self.detectKind(text), text: text, png: nil, source: source)
            return
        }
        // Imagem (png preferido, tiff como fallback)
        let imageType: NSPasteboard.PasteboardType? =
            types.contains(NSPasteboard.PasteboardType.png.rawValue) ? .png :
            (types.contains(NSPasteboard.PasteboardType.tiff.rawValue) ? .tiff : nil)
        if let imageType, let data = pasteboard.data(forType: imageType) {
            guard pasteboard.changeCount == before else { return }   // TOCTOU
            guard data.count <= Self.maxImageBytes else { return }
            imageTask?.cancel()
            imageTask = Task { [weak self] in
                let png = await Task.detached(priority: .utility) { Self.makeThumbnail(data) }.value
                guard !Task.isCancelled, let self, let png else { return }
                self.insert(kind: .image, text: nil, png: png, source: source)
            }
        }
    }

    private func insert(kind: ClipboardItem.Kind, text: String?, png: Data?, source: String?) {
        // Dedupe: mesmo conteúdo sobe para o topo (preserva fixação)
        var pinned = false
        var list = items
        if let idx = list.firstIndex(where: { $0.kind == kind && $0.text == text && $0.imagePNG == png }) {
            pinned = list[idx].isPinned
            list.remove(at: idx)
        }
        list.append(ClipboardItem(id: UUID(), kind: kind, text: text, imagePNG: png,
                                  sourceApp: source, date: Date(), isPinned: pinned))
        list = Self.ordered(list)   // único sort
        var unpinned = 0
        items = list.filter { it in
            if it.isPinned { return true }
            unpinned += 1
            return unpinned <= Self.maxUnpinned
        }
    }

    /// Fixados primeiro, depois por data decrescente.
    nonisolated static func ordered(_ list: [ClipboardItem]) -> [ClipboardItem] {
        let sorted = list.sorted { $0.date > $1.date }
        return sorted.filter(\.isPinned) + sorted.filter { !$0.isPinned }
    }

    // MARK: - Heurística de segredo (puro, testável)

    /// True se o texto parece um token/chave de API e NÃO deve ser guardado.
    nonisolated static func looksLikeSecret(_ text: String) -> Bool {
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard t.count >= 20, !t.contains(where: \.isWhitespace), !t.contains("://") else { return false }
        let prefixes = ["ghp_", "gho_", "ghu_", "ghs_", "github_pat_", "sk-", "sk_live_", "sk_test_",
                        "xoxa-", "xoxb-", "xoxp-"]
        if prefixes.contains(where: { t.hasPrefix($0) }) { return true }
        if t.hasPrefix("AKIA"), t.count >= 20, t.dropFirst(4).allSatisfy({ $0.isASCII && ($0.isUppercase || $0.isNumber) }) {
            return true
        }
        if t.hasPrefix("eyJ"), t.filter({ $0 == "." }).count == 2 { return true }
        guard t.count >= 32, !t.hasPrefix("/") else { return false }
        let hasLetter = t.contains { $0.isLetter }
        let hasDigit = t.contains { $0.isNumber }
        return hasLetter && hasDigit && shannonEntropy(t) >= 4.0
    }

    nonisolated static func shannonEntropy(_ s: String) -> Double {
        var freq: [Character: Int] = [:]
        for c in s { freq[c, default: 0] += 1 }
        let n = Double(s.count)
        return -freq.values.reduce(0.0) { $0 + (Double($1) / n) * log2(Double($1) / n) }
    }

    // MARK: - Detecção (puro, testável)

    nonisolated static func detectKind(_ text: String) -> ClipboardItem.Kind {
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if isHexColor(t) { return .color }
        if !t.contains(where: \.isWhitespace), let url = URL(string: t),
           let scheme = url.scheme?.lowercased(), scheme == "http" || scheme == "https",
           url.host?.isEmpty == false { return .link }
        return .text
    }

    nonisolated static func isHexColor(_ s: String) -> Bool {
        guard s.hasPrefix("#") else { return false }
        let hex = s.dropFirst()
        return (hex.count == 6 || hex.count == 8 || hex.count == 3) && hex.allSatisfy(\.isHexDigit)
    }

    /// Reduz para no máximo 160 px e codifica em PNG. Seguro fora da main thread.
    nonisolated static func makeThumbnail(_ data: Data) -> Data? {
        guard let src = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        let opts: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: Int(thumbnailMaxSide)
        ]
        guard let cg = CGImageSourceCreateThumbnailAtIndex(src, 0, opts as CFDictionary) else { return nil }
        let out = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(out, "public.png" as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(dest, cg, nil)
        return CGImageDestinationFinalize(dest) ? out as Data : nil
    }
}
